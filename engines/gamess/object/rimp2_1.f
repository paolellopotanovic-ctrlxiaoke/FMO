      LENT3 = NAUXBAS*NVIR
C
      E2T = ZERO
      E2S = ZERO
      DO JBAT = 1, NOCCBAT
         JOCCBG = INFOCCBAT(1,JBAT)+1
         JOCCED = INFOCCBAT(1,JBAT)+INFOCCBAT(2,JBAT)
         CALL TSECND(TIMER0)
         IF(SMP_ME .EQ. 0) THEN
