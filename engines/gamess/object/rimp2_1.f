            CALL DDI_SMP_SYNC()
         END DO                 !IBAT
      END DO                    !JBAT
      E2 = E2S+E2T
C
      IF(MASWRK) WRITE(IW,9999) TIMER,TIME4,TIME5
      CALL FLSHBF(IW)
      RETURN
