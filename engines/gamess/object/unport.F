#endif
            use iso_c_binding, only: c_int
            import
            integer(c_int) :: sleep
            integer(c_int), intent(in), value :: duration
          end function sleep
#if   ! defined(_WIN64)
C>
C>        @brief   Interface to POSIX fsync.
C>
C>        @details Transfers all modified in- core data
C>                 of the file referred to by fd to disk.
C>                 The call  blocks until the device
C>                 reports that the transfer has completed.
C>
C>        @author Christian Friedl
C>
C>        @date   Jul, 2022 Initial release
C>
          function fsync(fd) bind(c,name="fsync")
          use iso_c_binding, only: c_int
            integer(c_int), value :: fd
            integer(c_int) :: fsync
          end function fsync
C>
C>        @brief  Interface to getfd function.
C>
C>        @detail Returns the underlying file
C>                descriptor given a Fortran
C>                logical unit. Compiler dependent.
C>
C>        @author Christian Friedl
C>
C>        @date   Jul, 2022 Initial release
C>
#if   defined(__NVCOMPILER)
          function getfd(lu)
            integer(kind=4) :: lu
            integer(kind=4) :: getfd
          end function getfd
#elif defined(__AOCC__)
C         AOCC is hard to identify this is not a predefined macro
          function getfd(lu)
            integer(kind=4) :: lu
            integer(kind=4) :: getfd
