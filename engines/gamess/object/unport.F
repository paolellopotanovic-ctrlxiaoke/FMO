      MODULE UNPORT
        implicit none
C
C       The version string is also architecture dependent
C
#if     defined(_WIN64)
        character(len=40), parameter :: version_string =
     *    '******** 64 BIT WINDOWS VERSION ********'
#else
        character(len=40), parameter :: version_string =
     *    '********* 64 BIT LINUX VERSION *********'
#endif
#if     defined(_WIN64)
        character(len=1), parameter :: directory_separator = '\'
#else
        character(len=1), parameter :: directory_separator = '/'
#endif
C
C       Determines whether subroutine commit can be called
C
#if     defined(_WIN64) && defined(__INTEL_COMPILER)
        logical, parameter :: commit_supported = .true.
#elif ! defined(_WIN64) && defined(__GFORTRAN__)
        logical, parameter :: commit_supported = .true.
#elif ! defined(_WIN64) && defined(__INTEL_COMPILER)
        logical, parameter :: commit_supported = .true.
#elif ! defined(_WIN64) && defined(__NVCOMPILER)
        logical, parameter :: commit_supported = .true.
#elif ! defined(_WIN64) && defined(__AOCC__)
