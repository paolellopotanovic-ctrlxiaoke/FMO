        end interface
      contains
C>
C>      @brief  Commit dirty data of logical unit
C>              to stable storage.
C>
C>      @detail Blocks until the data is commited.
C>              Does nothing if compiler is
C>              unsupported or if the logical
C>              unit is not connected to a file.
C>
C>      @author Christian Friedl
C>
C>      @date   Jul, 2022 Initial release
C>
        subroutine commit(lu)
#if   defined(_WIN64)  &&  defined(__INTEL_COMPILER)
        use ifcore
        implicit none
        integer, intent(in) :: lu
        integer(kind=4) :: ret4
        logical :: retl
        integer(kind=4) :: lu4
        lu4 = int(lu, kind=4)
        retl = commitqq(lu4)
        return
#elif ! defined(_WIN64) && defined(__GFORTRAN__)
        implicit none
        integer, intent(in) :: lu
        integer(kind=4) :: ret4
        integer(kind=4) :: fd4, lu4
        lu4 = int(lu, kind=4)
        fd4 = fnum(lu4)
        ret4 = fsync(fd4)
        return
#elif ! defined(_WIN64) && defined(__INTEL_COMPILER)
        use ifposix
        implicit none
        integer, intent(in) :: lu
        integer(kind=4) :: ret4
        integer(kind=4) :: fd4, ierror4, lu4
        lu4 = int(lu, kind=4)
        call pxffileno(lu4, fd4, ierror4)
        if (ierror4 .ne. 0) return
        ret4 = fsync(fd4)
        return
#elif ! defined(_WIN64) && defined(__NVCOMPILER)
        implicit none
        integer, intent(in) :: lu
        integer(kind=4) :: fd4, lu4
        integer(kind=4) :: ret4
        lu4 = int(lu, kind=4)
        fd4 = getfd(lu4)
        if (fd4 .eq. -1) return
        ret4 = fsync(fd4)
        return
#elif ! defined(_WIN64) && defined(__AOCC__)
C       AOCC is hard to identify this is not a predefined macro
        implicit none
        integer, intent(in) :: lu
        integer(kind=4) :: ret4
        integer(kind=4) :: fd4, lu4
        lu4 = int(lu, kind=4)
        fd4 = getfd(lu4)
        if (fd4 .eq. -1) return
        ret4 = fsync(fd4)
        return
#elif ! defined(_WIN64) && defined(__ibmxl__)
        implicit none
        integer, intent(in) :: lu
        integer(kind=4) :: ret4
        integer(kind=4) :: fd4, lu4
        lu4 = int(lu, kind=4)
        fd4 = getfd_(lu4)
        if (fd4 .eq. -1) return
        ret4 = fsync(fd4)
        return
#else
C       Do nothing if compiler is unsupported.
        implicit none
        integer, intent(in) :: lu
        return
#endif
        end subroutine
