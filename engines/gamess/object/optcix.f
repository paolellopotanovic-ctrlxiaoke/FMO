      IF(SCFTYP.EQ.RMC) THEN
         IF(NFRG.GT.0) CALL ABRT
         NUMST = NSTATMC()
         M1 = NUMST
         M2 = (M1*(M1-1))/2
      ELSE IF(TDDFTYP.NE.RNONE) THEN
         NUMST = NSTAT
         M1 = 0
         M2 = 0
      ELSE IF(CITYP.EQ.SFORM) THEN
         NUMST=KDET
         M1=NUMST
         M2=(M1*(M1-1))/2
      END IF
