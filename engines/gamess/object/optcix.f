C     ----- MEMORY ALLOCATION -----
C
      CALL VALFM(LOADFM)
      LTMP = 1    + LOADFM
      LEG1 = LTMP + MAX(M1,M2)*NCVF
      LEG2 = LEG1 + NCVF
      LEG3 = LEG2 + NCVF
      LEG4 = LEG3 + NCVF
      LFV  = LEG4 + NCVF
      LWRK = LFV  + NCVF
      LWRK1 = LWRK  + NCVF
      LWRK2 = LWRK1  + NCVF
      LWRK3 = LWRK2  + NCVF
