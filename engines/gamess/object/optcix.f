      IF(NCNCL.EQ.4) THEN
         IF(ITSTAT(1).EQ.0) THEN
            ENG1 = ESCF
         ELSE
            ENG1 = ESCF + ESTATE(ITSTAT(1))
         END IF
         ENG2 = ESCF + ESTATE(ITSTAT(2))
