     *        NUMST,NCVF,IXROOT,IXSTAT,DEBUG)
      ELSE IF(TDDFTYP.NE.RNONE .AND. NCNCL.NE.4) THEN
         CALL DAREAD(IDAF,IODA,X(LEG1),NCVF,497,0)
         CALL EGMOVE(X(LEG2),EG,DEFT,TORQ,NCVAL,NFRG)
